/**
 * FoxESS Cloud HTTP client (web app API, `FOX_CLOUD_WEB_2_0`).
 *
 * Reconstructed from the v2 web bundle:
 *
 *   login    POST /foxess/biz/auth/login   { account, password: md5(password) }
 *   plants   POST /dew/w/v0/plant/list     { page, size, fuzzyCondition, status: 0, exportFlag: false }
 *   active   POST /dew/w/v0/plant/alarm    { plantID }
 *   history  POST /dew/w/v0/plant/historyAlarm { plantID, begin:{y,m,d}, end:{y,m,d}, realtimeFlag }
 *
 * Every request carries the same headers the SPA sends (`lang`, `token`,
 * `timezone`, `platform`, `X-Auth-Platform`, `dt`, `timestamp`, `signature`).
 * The `signature` is generated by the site's own WASM module; the server does
 * not appear to validate it today, but we send a correct one regardless.
 */

import { createHash } from 'node:crypto';

import { formatInZone, datePartsInZone } from '../time.js';
import { createSigner } from './signature.js';

const AUTH_ERRNOS = new Set([41808, 41809, 41810, 41819]);

const ERROR_HINTS = {
  401: 'FoxESS rejected the username or password (this endpoint reports bad credentials as errno 401).',
  41807: 'FoxESS rejected the credentials (wrong username or password).',
  41808: 'FoxESS says the session token is invalid (expired?).',
  41809: 'FoxESS says the session token is missing.',
  41810: 'FoxESS says the session token expired.',
  41819: 'FoxESS says the request is unauthorized (token expired or revoked).',
  40257: 'FoxESS rejected the request parameters. US accounts live on a separate stack: set FOXESS_BASE_URL=https://us.foxesscloud.com.',
};

export class FoxessApiError extends Error {
  constructor(message, { path, httpStatus, errno, hint, retryable = true } = {}) {
    super(message);
    this.name = 'FoxessApiError';
    this.path = path;
    this.httpStatus = httpStatus;
    this.errno = errno;
    this.hint = hint;
    // Bad credentials, a missing token or a rejected payload will never succeed
    // on a second attempt, so the caller must not burn the retry budget on them.
    this.retryable = retryable;
  }
}

/** errno values that mean "the request itself is wrong", not "try again". */
const FATAL_ERRNOS = new Set([401, 41807, 40257]);

export function md5(value) {
  return createHash('md5').update(String(value)).digest('hex');
}

/** Pulls the session token out of a login response without knowing its field name. */
export function extractToken(payload, headers) {
  const candidates = [
    payload?.token,
    payload?.accessToken,
    payload?.access_token,
    payload?.tokenValue,
    payload?.result?.token,
    headers?.get?.('refreshed-token'),
  ].filter((value) => typeof value === 'string' && value.trim().length > 8);
  if (candidates.length) return { token: candidates[0].trim(), field: 'known-field' };

  // FoxESS tokens look like `biz-web-<uuid>`; fall back to shape matching, then
  // to any key that looks like a token.
  const seen = new Set();
  const visit = (node, depth) => {
    if (!node || typeof node !== 'object' || depth > 4 || seen.has(node)) return null;
    seen.add(node);
    for (const [key, value] of Object.entries(node)) {
      if (typeof value === 'string' && /^[a-z0-9-]*web-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)) {
        return { token: value, field: key };
      }
    }
    for (const value of Object.values(node)) {
      const found = value && typeof value === 'object' ? visit(value, depth + 1) : null;
      if (found) return found;
    }
    return null;
  };

  const byShape = visit(payload, 0);
  if (byShape) return byShape;

  const byKey = visitKey(payload, 0, seen);
  return byKey ?? { token: null, field: null };
}

function visitKey(node, depth, seen) {
  if (!node || typeof node !== 'object' || depth > 4) return null;
  for (const [key, value] of Object.entries(node)) {
    if (typeof value === 'string' && value.length > 12 && /token/i.test(key)) return { token: value, field: key };
  }
  for (const value of Object.values(node)) {
    if (value && typeof value === 'object' && !seen.has(value)) {
      const found = visitKey(value, depth + 1, seen);
      if (found) return found;
    }
  }
  return null;
}

export function createApiClient(config, logger, { fetchImpl = globalThis.fetch } = {}) {
  const { api, foxess } = config;
  const signer = createSigner(config, logger);

  let token = api.token || null;
  let loginPromise = null;

  const log = logger.child('api');

  function zone(explicit) {
    return explicit || foxess.timezone || 'UTC';
  }

  async function buildHeaders(path, { timezone, useToken = true } = {}) {
    const timestamp = Date.now();
    const tz = zone(timezone);
    const lang = foxess.lang;
    const [signature] = await Promise.all([signer.sign(path, useToken ? token ?? '' : '', lang, timestamp)]);
    return {
      accept: 'application/json, text/plain, */*',
      'content-type': 'application/json',
      contentType: 'application/json',
      lang,
      token: useToken ? token ?? '' : '',
      timezone: tz,
      platform: 'web',
      'X-Auth-Platform': 'FOX_CLOUD_WEB_2_0',
      dt: `${tz}@${timestamp}@${formatInZone(new Date(timestamp), tz)}`,
      timestamp: String(timestamp),
      signature,
    };
  }

  async function send(method, path, body, { timezone, useToken = true } = {}) {
    const headers = await buildHeaders(path, { timezone, useToken });
    const response = await fetchImpl(`${foxess.baseUrl}${path}`, {
      method,
      headers: { ...headers, origin: foxess.baseUrl, referer: `${foxess.baseUrl}/v2/` },
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: AbortSignal.timeout(api.timeoutMs),
    });

    const refreshed = response.headers.get('refreshed-token');
    if (refreshed && refreshed !== token) {
      token = refreshed;
      log.debug('token refreshed from response header');
    }

    const text = await response.text();
    let payload = null;
    try {
      payload = text ? JSON.parse(text) : null;
    } catch {
      throw new FoxessApiError(`Non-JSON response from ${path} (HTTP ${response.status}): ${text.slice(0, 200)}`, {
        path,
        httpStatus: response.status,
      });
    }

    return { status: response.status, payload, headers: response.headers };
  }

  function errorFrom(path, status, payload) {
    const errno = Number(payload?.errno);
    const message = payload?.msg ? String(payload.msg) : `HTTP ${status}`;
    const hint = ERROR_HINTS[errno];
    const retryable = !FATAL_ERRNOS.has(errno) && status !== 401 && status !== 403;
    return new FoxessApiError(`${path} failed: ${errno ? `${errno} ` : ''}${message}`, {
      path,
      httpStatus: status,
      errno: Number.isFinite(errno) ? errno : undefined,
      hint,
      retryable,
    });
  }

  async function request(method, path, body, { timezone, useToken = true, retryOnAuth = true } = {}) {
    // Callers should not have to remember to authenticate first.
    if (useToken && !token) await login();

    const { status, payload } = await send(method, path, body, { timezone, useToken });

    if (status === 401 || status === 403) throw errorFrom(path, status, payload);

    const errno = Number(payload?.errno ?? 0);
    if (errno !== 0) {
      if (retryOnAuth && AUTH_ERRNOS.has(errno) && !loginPromise) {
        log.warn('session rejected, re-authenticating', { path, errno });
        await login({ force: true });
        return request(method, path, body, { timezone, useToken, retryOnAuth: false });
      }
      throw errorFrom(path, status, payload);
    }
    return payload;
  }

  async function performLogin() {
    if (api.token) return api.token;
    if (!foxess.username || !foxess.password) {
      throw new FoxessApiError('No credentials configured: set FOXESS_USERNAME and FOXESS_PASSWORD (or FOXESS_TOKEN).', {
        path: api.loginPath,
      });
    }

    const password = md5(foxess.password);
    const attempts = [
      { path: api.loginPath, body: { account: foxess.username, password } },
      // Accounts routed through the US stack use a different endpoint/payload.
      { path: '/basic/v0/user/login', body: { user: foxess.username, password, type: 1, verification: 1 } },
    ];

    let lastError = null;
    for (const attempt of attempts) {
      try {
        const payload = await request('POST', attempt.path, attempt.body, { useToken: false, retryOnAuth: false });
        const { token: newToken, field } = extractToken(payload, undefined);
        if (!newToken) {
          throw new FoxessApiError(
            `Login succeeded but no token was found in the response (keys: ${Object.keys(payload?.result ?? {}).join(', ') || 'none'}).`,
            { path: attempt.path, retryable: false },
          );
        }
        token = newToken;
        log.info('logged in', { path: attempt.path, tokenField: field });
        return token;
      } catch (error) {
        lastError = error;
        const tryNext = error.httpStatus === 404 || error.httpStatus === 405;
        log.debug('login attempt failed', { path: attempt.path, errno: error.errno, status: error.httpStatus });
        if (!tryNext) break;
      }
    }
    throw lastError;
  }

  async function login({ force = false } = {}) {
    if (token && !force) return token;
    if (!loginPromise) {
      loginPromise = performLogin().finally(() => {
        loginPromise = null;
      });
    }
    return loginPromise;
  }

  return {
    get token() {
      return token;
    },

    get signerMode() {
      return signer.mode;
    },

    login,
    ensureToken: () => login(),

    /**
     * Plant detail. `plant/list` does not carry the timezone, but alarm
     * timestamps are plant-local, so this is where the zone comes from.
     */
    async getPlantDetail(plantID) {
      const payload = await request('GET', `/dew/w/v0/plant/detail?plantID=${encodeURIComponent(plantID)}`);
      return payload?.result?.info ?? null;
    },

    async userInfo() {
      const payload = await request('GET', '/basic/w/v0/user/info');
      return payload?.result ?? null;
    },

    async listPlants({ pageSize = 100 } = {}) {
      const plants = [];
      const seen = new Set();
      for (let page = 1; page <= 20; page += 1) {
        const payload = await request('POST', '/dew/w/v0/plant/list', {
          page,
          size: pageSize,
          fuzzyCondition: '',
          status: 0,
          exportFlag: false,
        });
        const result = payload?.result ?? {};
        const data = Array.isArray(result.data) ? result.data : [];
        for (const plant of data) {
          const id = plant?.plantID ?? plant?.id;
          if (!id || seen.has(id)) continue;
          seen.add(id);
          plants.push(plant);
        }
        const total = Number(result.total ?? plants.length);
        if (!data.length || plants.length >= total) break;
      }
      log.debug('plants listed', { count: plants.length });
      return plants;
    },

    /** Currently active alarms for one plant. */
    async listActiveAlarms(plantID, { timezone } = {}) {
      const payload = await request(
        'POST',
        '/dew/w/v0/plant/alarm',
        { plantID, category: null, severity: null, device: null },
        { timezone },
      );
      const result = payload?.result ?? {};
      const alarms = Array.isArray(result.alarmList) ? result.alarmList : [];
      return { alarms, count: Number(result.alarmCount ?? alarms.length), meta: result };
    },

    /**
     * Alarms that occurred in the given range (includes recovered ones).
     *
     * The API silently returns nothing for wide ranges - the web app caps the
     * picker at 14 days - so the range is queried in chunks and merged.
     */
    async listHistoryAlarms(plantID, { from, to, timezone } = {}) {
      const tz = zone(timezone);
      const chunkMs = Math.max(1, api.historyChunkDays) * 24 * 60 * 60 * 1000;
      const alarms = [];
      const seen = new Set();

      let cursor = new Date(from);
      const limit = new Date(to);
      let windows = 0;

      while (cursor <= limit && windows < 200) {
        windows += 1;
        const windowEnd = new Date(Math.min(cursor.getTime() + chunkMs, limit.getTime()));
        const payload = await request(
          'POST',
          '/dew/w/v0/plant/historyAlarm',
          {
            plantID,
            exportFlag: false,
            begin: datePartsInZone(cursor, tz),
            end: datePartsInZone(windowEnd, tz),
            realtimeFlag: false,
            category: null,
            severity: null,
            device: null,
          },
          { timezone: tz },
        );

        const result = payload?.result ?? {};
        for (const alarm of Array.isArray(result.alarmList) ? result.alarmList : []) {
          // Boundary days are queried twice; the identity key keeps them unique.
          const key = `${alarm.device ?? ''}|${alarm.code ?? ''}|${alarm.date ?? ''}|${alarm.category ?? ''}`;
          if (seen.has(key)) continue;
          seen.add(key);
          alarms.push(alarm);
        }

        if (windowEnd.getTime() >= limit.getTime()) break;
        cursor = new Date(windowEnd.getTime() + 24 * 60 * 60 * 1000);
      }

      log.debug('history queried', { plantID, windows, rows: alarms.length, from: from?.toISOString?.(), to: to?.toISOString?.() });
      return { alarms, count: alarms.length, windows };
    },
  };
}
